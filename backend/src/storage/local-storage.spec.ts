import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { LocalStorage } from './local-storage.js';

const KEY =
  'cvs/10000000-0000-0000-0000-000000000001/3f1c2b7e-9d3a-4c4e-8a51-0d2b6f7e9a10.pdf';

describe('LocalStorage', () => {
  let directory: string;
  let storage: LocalStorage;

  beforeAll(async () => {
    directory = await mkdtemp(join(tmpdir(), 'local-storage-'));
    storage = new LocalStorage(directory, 'http://api.test', 'secret');
  });

  afterAll(() => rm(directory, { recursive: true, force: true }));

  const paramsOf = async (key: string, name?: string) => {
    const url = new URL(await storage.signedUrl(key, name));
    const params = url.searchParams;
    return {
      url,
      signed: {
        key: params.get('key')!,
        expires: Number(params.get('expires')),
        name: params.get('name') ?? undefined,
      },
      signature: params.get('signature')!,
    };
  };

  it('signs links that it accepts back, for the file they name', async () => {
    const { url, signed, signature } = await paramsOf(KEY, 'cv.pdf');

    expect(url.origin + url.pathname).toBe('http://api.test/api/files');
    expect(storage.verify(signed, signature)).toBe(join(directory, KEY));
  });

  it('gives the same link for a while, so that browsers can cache it', async () => {
    expect((await paramsOf(KEY)).url.href).toBe((await paramsOf(KEY)).url.href);
  });

  it('rejects a changed name, key or expiry, and an expired link', async () => {
    const { signed, signature } = await paramsOf(KEY, 'cv.pdf');

    expect(
      storage.verify({ ...signed, name: 'other.pdf' }, signature),
    ).toBeNull();
    expect(
      storage.verify(
        { ...signed, key: KEY.replace('.pdf', '.png') },
        signature,
      ),
    ).toBeNull();
    expect(
      storage.verify({ ...signed, expires: signed.expires + 1 }, signature),
    ).toBeNull();
    expect(
      storage.verify(
        { ...signed, expires: Math.floor(Date.now() / 1000) - 1 },
        signature,
      ),
    ).toBeNull();
  });

  it('only accepts keys generated by the API', async () => {
    await expect(
      storage.put('../outside.pdf', Buffer.from('x')),
    ).rejects.toThrow('Invalid storage key');
    await expect(
      storage.signedUrl('cvs/../../etc/passwd'),
    ).resolves.toBeTruthy();
    const { signed, signature } = await paramsOf('cvs/../../etc/passwd');
    expect(() => storage.verify(signed, signature)).toThrow(
      'Invalid storage key',
    );
  });
});
